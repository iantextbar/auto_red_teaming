from matrix import Matrix, Stance, parse_stances, render, run

DEBATE_BODY = """## Question

Does AI speed up experienced developers?

## Positions

### Speeds up

Prose.

### Slows down

Prose.

## Why they differ

## Stances

- [[becker-2025]] · Slows down · supports · (p. 1)
- [[notes/20-sources/peng-2023.md|Peng]] · Speeds up · qualifies · (p. 2, p. 8)
- [[shen-2026]] · Slows down · supports
- [[merola-2026]] · Slower · contests · (p. 3)

## Reading
"""


def test_parse_stances_reads_well_formed_lines():
    stances, _ = parse_stances("speed", DEBATE_BODY)
    assert stances == [
        Stance("speed", "becker-2025", "Slows down", "supports", "(p. 1)"),
        Stance("speed", "peng-2023", "Speeds up", "qualifies", "(p. 2, p. 8)"),
    ]


def test_line_without_anchor_and_unknown_position_are_problems():
    _, problems = parse_stances("speed", DEBATE_BODY)
    assert problems == [
        "malformed stance line: - [[shen-2026]] · Slows down · supports",
        "position not under ## Positions: Slower",
    ]


def test_render_groups_by_source_with_interest():
    matrix = Matrix(
        stances=[
            Stance("time", "becker-2025", "Slows down", "supports", "(p. 1)"),
            Stance("perception", "becker-2025", "Divergence", "supports", "(p. 3)"),
            Stance("time", "alenezi-2026", "Speeds up", "supports", "(p. 12)"),
        ],
        interests={"becker-2025": "independent"},
    )
    assert render(matrix) == (
        "# Matrix\n\nGenerated by scripts/matrix.py; do not edit.\n\n"
        "## [[alenezi-2026]]\n\n"
        "- [[time]] · Speeds up · supports · (p. 12)\n\n"
        "## [[becker-2025]] · independent\n\n"
        "- [[perception]] · Divergence · supports · (p. 3)\n"
        "- [[time]] · Slows down · supports · (p. 1)\n"
    )


def test_render_without_stances():
    assert render(Matrix()).endswith("No stances yet.\n")


def test_run_writes_matrix_and_reads_interest(tmp_path):
    (tmp_path / "10-debates").mkdir()
    (tmp_path / "20-sources").mkdir()
    (tmp_path / "90-meta").mkdir()
    (tmp_path / "10-debates" / "speed.md").write_text(
        "---\ntype: debate\n---\n\n" + DEBATE_BODY, encoding="utf-8"
    )
    (tmp_path / "20-sources" / "becker-2025.md").write_text(
        "---\ntype: source\ninterest: independent\n---\n\n## Stated by the source\n",
        encoding="utf-8",
    )
    matrix = run(tmp_path)
    text = (tmp_path / "90-meta" / "matrix.md").read_text(encoding="utf-8")
    assert "## [[becker-2025]] · independent" in text
    assert "## [[peng-2023]]\n" in text  # no source note: no interest, no crash
    assert len(matrix.problems) == 2
