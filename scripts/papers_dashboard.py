"""Generate notes/90-meta/papers-dashboard.md: progress of the three papers in the evidence map.

    uv run scripts/papers_dashboard.py [--json PATH]

Reporting only, no interpretation (CLAUDE.md §1): it counts what the vault records. Inputs:

- `notes/30-positions/paper-ideas-evidence-map.md` — papers, questions, "What has been
  investigated" (with source keys), "Evidence type", "Open (draft)", "Source key", "Gaps";
- `notes/20-sources/*.md` — `status`, `reviewed_by`, `source_type`, `interest`, `pdf`, and whether
  `### Empirical base` reports data of the source's own ("None of its own", "No original",
  "Secondary" count as no own data — the note's wording, not an assessment);
- `notes/10-debates/*.md` — `sources:` of each debate, to show which debates each question touches;
- `docs/roadmap.md` — checked boxes per phase;
- git history — number of source and debate notes at each commit that changed them.

`--json PATH` also writes the same figures as JSON (used to publish an HTML view elsewhere).
"""

from __future__ import annotations

import argparse
import csv
import json
import re
import subprocess
from datetime import date
from pathlib import Path

from claims_index import link_target
from vault import read_note, sections, subsections

ROOT = Path(__file__).resolve().parent.parent
NOTES = ROOT / "notes"
EVIDENCE_MAP = NOTES / "30-positions" / "paper-ideas-evidence-map.md"
OUT = NOTES / "90-meta" / "papers-dashboard.md"
GENERATED = "Generated by scripts/papers_dashboard.py; do not edit."
WIKILINK = re.compile(r"\[\[([^\]|#]+)(?:[#|][^\]]*)?\]\]")
NO_OWN_DATA = re.compile(
    r"^\W*(none of its own|no original|no new|secondary|not applicable|none\b)", re.I
)
# categorical slots 1-2 of the validated palette (dataviz skill, light mode)
COLORS = "#2a78d6, #eb6834"


def git(*args: str) -> str:
    return subprocess.run(
        ["git", *args], cwd=ROOT, capture_output=True, text=True, check=True
    ).stdout


def own_data(body: str) -> str:
    stated = subsections(sections(body).get("Stated by the source", ""))
    base = (stated.get("Empirical base") or "").strip()
    if not base:
        return "not recorded"
    return "no own data" if NO_OWN_DATA.match(base) else "own data"


def load_sources() -> dict[str, dict]:
    out = {}
    for f in sorted((NOTES / "20-sources").glob("*.md")):
        n = read_note(f)
        out[f.stem] = {
            "status": str(n.meta.get("status") or ""),
            "reviewed": bool(str(n.meta.get("reviewed_by") or "").strip()),
            "source_type": str(n.meta.get("source_type") or ""),
            "interest": str(n.meta.get("interest") or ""),
            "pdf": bool(str(n.meta.get("pdf") or "").strip()),
            "data": own_data(n.body),
        }
    return out


def load_debates() -> dict[str, dict]:
    out = {}
    for f in sorted((NOTES / "10-debates").glob("*.md")):
        n = read_note(f)
        srcs = {
            link_target(s)
            for s in WIKILINK.findall(" ".join(map(str, n.meta.get("sources") or [])))
        }
        out[f.stem] = {
            "question": str(n.meta.get("question") or "").strip(),
            "sources": srcs,
            "reviewed": bool(str(n.meta.get("reviewed_by") or "").strip()),
        }
    return out


def cell_split(line: str) -> list[str]:
    return [c.strip() for c in line.strip().strip("|").split("|")]


def parse_evidence_map() -> tuple[list[dict], dict[str, str], list[str], list[str]]:
    body = read_note(EVIDENCE_MAP).body
    problems: list[str] = []
    parts = sections(body)
    keys = {}
    for line in subsections(parts.get("Positions", "")).get("Source key", "").splitlines():
        m = re.match(r"^\s*-?\s*(.+?):\s*\[\[([^\]]+)\]\]", line)
        if m:
            keys[m.group(1).strip()] = link_target(m.group(2))
    papers = []
    for head, text in subsections(parts.get("Positions", "")).items():
        m = re.match(r"Paper (\d): (.+)", head)
        if not m:
            continue
        question = next(
            (
                ln.strip()
                for ln in text.splitlines()
                if ln.strip() and not ln.lstrip().startswith("|")
            ),
            "",
        )
        rows = []
        for line in text.splitlines():
            c = cell_split(line)
            if len(c) < 4 or c[0] in ("Question", "") or set(c[0]) <= set("-: "):
                continue
            if len(c) > 4:
                # an unescaped "|" inside a cell splits it; the first, the last two and the
                # rest are still recoverable, and the problem is reported, not fixed
                problems.append(
                    f"Paper {m.group(1)}, row '{c[0]}': {len(c) - 4} unescaped '|' inside a cell"
                    " (the table renders broken; escape it as a backslash-pipe)"
                )
                c = [c[0], "|".join(c[1:-2]), c[-2], c[-1]]
            rows.append(
                {"question": c[0], "investigated": c[1], "evidence_type": c[2], "open": c[3]}
            )
        papers.append(
            {"n": int(m.group(1)), "title": m.group(2).strip(), "question": question, "rows": rows}
        )
    gaps = [
        ln.strip()[2:] if ln.strip().startswith("- ") else ln.strip()
        for ln in parts.get("Gaps", "").splitlines()
        if ln.strip() and not ln.startswith("#")
    ]
    return papers, keys, gaps, problems


def cited_keys(text: str, keys: dict[str, str]) -> set[str]:
    """Source keys cited in a cell, longest key first so 'Hassan 2025' is not read as 'Hassan'."""
    found, rest = set(), text
    for k in sorted(keys, key=len, reverse=True):
        pat = re.compile(rf"(?<![\w-]){re.escape(k)}(?=[,;) ]|$)")
        if pat.search(rest):
            found.add(keys[k])
            rest = pat.sub(" ", rest)
    return found


def roadmap() -> list[dict]:
    text = (ROOT / "docs" / "roadmap.md").read_text(encoding="utf-8")
    out = []
    for m in re.finditer(r"^## (Phase \d+[^\n]*)\n(.*?)(?=^## |\Z)", text, re.M | re.S):
        done = len(re.findall(r"^- \[x\]", m.group(2), re.M))
        todo = len(re.findall(r"^- \[ \]", m.group(2), re.M))
        out.append({"phase": m.group(1).strip(), "done": done, "total": done + todo})
    return out


def history() -> list[dict]:
    out: dict[str, dict] = {}
    for line in git(
        "log",
        "--reverse",
        "--format=%h %ad",
        "--date=short",
        "--",
        "notes/20-sources",
        "notes/10-debates",
    ).splitlines():
        h, d = line.split()
        files = git("ls-tree", "-r", "--name-only", h, "notes").splitlines()
        out[d] = {
            "commit": h,
            "date": d,  # last commit of each day
            "sources": sum(
                1 for f in files if f.startswith("notes/20-sources/") and f.endswith(".md")
            ),
            "debates": sum(
                1 for f in files if f.startswith("notes/10-debates/") and f.endswith(".md")
            ),
        }
    return sorted(out.values(), key=lambda x: x["date"])


LEVANTAMENTO = ROOT / "levantamento" / "dados" / "paper1"


def levantamento() -> dict | None:
    """Per-technique counts from the external survey snapshot (levantamento/, PR #2), if present.

    Discovery instrument outside the vault's sources (levantamento/README.md): counts are
    model-classified and reported as they are, with that caveat, never as source notes.
    """
    tec, top = LEVANTAMENTO / "paper1_tecnicas.csv", LEVANTAMENTO / "paper1_mais_citados.csv"
    if not tec.exists():
        return None
    with tec.open(encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    for r in rows:
        for k, v in r.items():
            if k not in ("tecnica", "linha_paper1", "criterio"):
                r[k] = int(v)
    cited: dict[str, list] = {}
    if top.exists():
        with top.open(encoding="utf-8") as f:
            for r in csv.DictReader(f):
                cited.setdefault(r["tecnica"], []).append(r)
    years = sorted(int(k[2:]) for k in rows[0] if re.fullmatch(r"n_\d{4}", k)) if rows else []
    return {"techniques": rows, "most_cited": cited, "years": years}


def build() -> dict:
    sources, debates = load_sources(), load_debates()
    papers, keys, gaps, problems = parse_evidence_map()
    for p in papers:
        p_srcs, p_debs = set(), set()
        for i, r in enumerate(p["rows"], 1):
            s = {k for k in cited_keys(r["investigated"] + " " + r["open"], keys) if k in sources}
            r["code"] = f"P{p['n']}.{i}"
            r["sources"] = sorted(s)
            r["own_data"] = sum(1 for k in s if sources[k]["data"] == "own data")
            r["no_own_data"] = sum(1 for k in s if sources[k]["data"] == "no own data")
            r["debates"] = sorted(d for d, v in debates.items() if v["sources"] & s)
            r["annotation_only"] = len(
                re.findall(r"annotation §", r["investigated"] + " " + r["open"])
            )
            p_srcs |= s
            p_debs |= set(r["debates"])
        p["sources"] = sorted(p_srcs)
        p["debates"] = sorted(p_debs)
        p["reviewed"] = sum(1 for k in p_srcs if sources[k]["reviewed"])
        p["own_data"] = sum(1 for k in p_srcs if sources[k]["data"] == "own data")
    status: dict[str, int] = {}
    for v in sources.values():
        status[v["status"] or "(empty)"] = status.get(v["status"] or "(empty)", 0) + 1
    return {
        "generated": date.today().isoformat(),
        "commit": git("rev-parse", "--short", "HEAD").strip(),
        "papers": papers,
        "problems": problems,
        "gaps": gaps,
        "roadmap": roadmap(),
        "history": history(),
        "vault": {
            "sources": len(sources),
            "debates": len(debates),
            "sources_reviewed": sum(v["reviewed"] for v in sources.values()),
            "debates_reviewed": sum(v["reviewed"] for v in debates.values()),
            "pdf": sum(v["pdf"] for v in sources.values()),
            "status": status,
            "own_data": sum(v["data"] == "own data" for v in sources.values()),
            "no_own_data": sum(v["data"] == "no own data" for v in sources.values()),
        },
        "debate_questions": {d: v["question"] for d, v in debates.items()},
        "levantamento": levantamento(),
    }


def short(t: str, n: int) -> str:
    t = re.sub(r"\s+", " ", WIKILINK.sub(lambda m: m.group(1), t)).strip()
    return t if len(t) <= n else t[: n - 1].rsplit(" ", 1)[0] + "…"


def mermaid_bar(title: str, labels: list[str], values: list[int], y: str) -> str:
    return "\n".join(
        [
            "```mermaid",
            "%%{init: {'themeVariables': {'xyChart': {'plotColorPalette': '"
            + COLORS.split(",")[0]
            + "'}}}}%%",
            "xychart-beta",
            f'    title "{title}"',
            "    x-axis [" + ", ".join(f'"{lab}"' for lab in labels) + "]",
            f'    y-axis "{y}" 0 --> {max(values + [1]) + 1}',
            "    bar [" + ", ".join(map(str, values)) + "]",
            "```",
        ]
    )


def row(*cells: object) -> str:
    return "| " + " | ".join(str(c) for c in cells) + " |"


def render_md(d: dict) -> str:
    v = d["vault"]
    L = [
        "---",
        "type: meta",
        "---",
        "",
        "# Papers dashboard",
        "",
        f"> {GENERATED} Source: `{EVIDENCE_MAP.relative_to(ROOT).as_posix()}` and the notes "
        f"it cites, commit `{d['commit']}`, {d['generated']}. Counts only: what the vault "
        "records, not what the "
        'evidence is worth (CLAUDE.md §1). "Own data" follows each note\'s `### Empirical base`.',
        "",
        "## Vault at a glance",
        "",
        row(
            "Source notes",
            "Debates",
            "Sources reviewed by a contributor",
            "Debates reviewed",
            "PDFs linked",
            "Sources with own data",
        ),
        "|---|---|---|---|---|---|",
        row(
            v["sources"],
            v["debates"],
            f"{v['sources_reviewed']} of {v['sources']}",
            f"{v['debates_reviewed']} of {v['debates']}",
            v["pdf"],
            f"{v['own_data']} (no own data: {v['no_own_data']})",
        ),
        "",
        "Source status: "
        + " · ".join(f"`{k}` {n}" for k, n in sorted(d["vault"]["status"].items())),
        "",
        "## The three papers",
        "",
        row(
            "Paper",
            "Questions",
            "Distinct sources cited",
            "With own data",
            "Reviewed by a contributor",
            "Debates touched",
        ),
        "|---|---|---|---|---|---|",
    ]
    for p in d["papers"]:
        L.append(
            row(
                f"**{p['n']}** — {p['title']}",
                len(p["rows"]),
                len(p["sources"]),
                p["own_data"],
                f"{p['reviewed']} of {len(p['sources'])}",
                len(p["debates"]),
            )
        )
    labels = [r["code"] for p in d["papers"] for r in p["rows"]]
    L += [
        "",
        mermaid_bar(
            "Vault sources cited per question",
            labels,
            [len(r["sources"]) for p in d["papers"] for r in p["rows"]],
            "sources",
        ),
        "",
    ]
    hist = d["history"]
    if hist:
        L += [
            "## Evolution",
            "",
            mermaid_bar(
                "Source notes in the vault, by commit",
                [h["date"] for h in hist],
                [h["sources"] for h in hist],
                "source notes",
            ),
            "",
            "| Date | Commit | Source notes | Debates |",
            "|---|---|---|---|",
        ]
        L += [f"| {h['date']} | `{h['commit']}` | {h['sources']} | {h['debates']} |" for h in hist]
        L.append("")
    L += ["## Vault build (docs/roadmap.md)", "", "| Phase | Done |", "|---|---|"]
    L += [f"| {r['phase']} | {r['done']} of {r['total']} |" for r in d["roadmap"]]
    L.append("")
    for p in d["papers"]:
        L += [
            f"## Paper {p['n']} — {p['title']}",
            "",
            f"*{p['question']}*",
            "",
            row(
                "#",
                "Question",
                "Sources",
                "Own data / none",
                "`annotation §` refs",
                "Debates",
                "Open (draft), first lines",
            ),
            "|---|---|---|---|---|---|---|",
        ]
        for r in p["rows"]:
            debs = ", ".join(f"[[{x}]]" for x in r["debates"]) or "—"
            L.append(
                row(
                    r["code"],
                    short(r["question"], 90),
                    len(r["sources"]),
                    f"{r['own_data']} / {r['no_own_data']}",
                    r["annotation_only"],
                    debs,
                    short(r["open"], 220),
                )
            )
        L.append("")
        if p["n"] == 1 and d.get("levantamento"):
            L += render_levantamento(d["levantamento"])
    L += (
        ["## Gaps recorded in the evidence map", ""]
        + [f"- {short(g, 400)}" for g in d["gaps"]]
        + [""]
    )
    if d["problems"]:
        L += ["## Format problems in the evidence map", ""]
        L += [f"- {x}" for x in d["problems"]] + [""]
    return "\n".join(L)


def render_levantamento(lv: dict) -> list[str]:
    ys = lv["years"]
    L = [
        "### Paper 1 × external survey (levantamento)",
        "",
        "> From `levantamento/dados/paper1/` (PR #2 snapshot; relevant papers 2021–2026). A",
        "> discovery instrument, not vault sources: techniques are counted by model-classified",
        "> `paradigma_interacao` or `tema_principal` (model-vs-persona κ 0.11 for paradigm), so",
        "> read the counts as order of magnitude. *Hand-annotated* = read by the base's annotator.",
        "",
        row(
            "Line",
            "Technique",
            "Papers",
            *[str(y) for y in ys],
            "Controlled experiments",
            "Measure productivity",
            "Industry setting",
            "Benchmark setting",
            "Hand-annotated",
        ),
        "|" + "---|" * (8 + len(ys)),
    ]
    for r in lv["techniques"]:
        L.append(
            row(
                r["linha_paper1"],
                r["tecnica"],
                r["n"],
                *[r[f"n_{y}"] for y in ys],
                r["experimento"],
                r["mede_produtividade"],
                r["cenario_industria"],
                r["cenario_benchmark"],
                r["anotados_a_mao"],
            )
        )
    L += [
        "",
        mermaid_bar(
            "Controlled experiments per technique (external survey)",
            [r["tecnica"] for r in lv["techniques"]],
            [r["experimento"] for r in lv["techniques"]],
            "experiments",
        ),
        "",
    ]
    L += ["Most cited per technique (titles as indexed; check before citing):", ""]
    for tec, items in lv["most_cited"].items():
        refs = "; ".join(
            f"{short(i['titulo'], 80)} ({i['ano']}, {i['citacoes']} cit., `{i['referencia']}`)"
            for i in items[:3]
        )
        L.append(f"- **{tec}**: {refs}")
    return L + [""]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--json", type=Path, help="also write the figures as JSON")
    a = ap.parse_args()
    d = build()
    OUT.write_text(render_md(d), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    if a.json:
        a.json.write_text(json.dumps(d, ensure_ascii=False, indent=1), encoding="utf-8")
        print(f"wrote {a.json}")


if __name__ == "__main__":
    main()
