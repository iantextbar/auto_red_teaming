"""Generate notes/90-meta/matrix.md: where each source stands across the debates.

    uv run scripts/matrix.py

Reads the `## Stances` lines of every debate in notes/10-debates/ and writes one list per source:
the debates it takes a stance in, with position, stance and anchor. A list per source, not a
sources x debates table, so the file stays readable as debates grow (docs/decisions.md, D28).

A stance line must have the form

    - [[source note]] · <position> · supports | contests | qualifies · (anchor)

and its position must be a `###` heading under the debate's `## Positions`. A line that breaks
either rule is reported and left out. Exits 1 if any line or note was malformed.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

from claims_index import link_target
from vault import NoteFormatError, read_note, sections, subsections

ROOT = Path(__file__).resolve().parent.parent
NOTES_ROOT = ROOT / "notes"

STANCE = re.compile(
    r"^- \[\[(?P<target>[^\]|#]+)(?:[#|][^\]]*)?\]\] · (?P<position>.+?) · "
    r"(?P<stance>supports|contests|qualifies) · (?P<anchor>\((?:pp?\.|¶|§) [^()]*\))$"
)
GENERATED = "Generated by scripts/matrix.py; do not edit."


@dataclass(frozen=True)
class Stance:
    debate: str
    source: str
    position: str
    stance: str
    anchor: str


@dataclass
class Matrix:
    stances: list[Stance] = field(default_factory=list)
    interests: dict[str, str] = field(default_factory=dict)  # source note -> interest
    problems: list[str] = field(default_factory=list)


# --- pure transformation -------------------------------------------------------------------


def parse_stances(debate: str, body: str) -> tuple[list[Stance], list[str]]:
    """The debate's stance lines, and a problem for each line that breaks the form."""
    parts = sections(body)
    positions = {p for p in subsections(parts.get("Positions", "")) if p}
    stances, problems = [], []
    for line in parts.get("Stances", "").splitlines():
        if not line.startswith("- "):
            continue
        m = STANCE.match(line.rstrip())
        if not m:
            problems.append(f"malformed stance line: {line.strip()}")
        elif m.group("position") not in positions:
            problems.append(f"position not under ## Positions: {m.group('position')}")
        else:
            stances.append(
                Stance(
                    debate,
                    link_target(m.group("target")),
                    m.group("position"),
                    m.group("stance"),
                    m.group("anchor"),
                )
            )
    return stances, problems


def render(matrix: Matrix) -> str:
    lines = ["# Matrix", "", GENERATED]
    by_source: dict[str, list[Stance]] = {}
    for s in sorted(matrix.stances, key=lambda s: (s.source, s.debate)):
        by_source.setdefault(s.source, []).append(s)
    if not by_source:
        lines += ["", "No stances yet."]
    for source, stances in by_source.items():
        header = " · ".join(filter(None, [f"[[{source}]]", matrix.interests.get(source, "")]))
        lines += ["", f"## {header}", ""]
        lines += [f"- [[{s.debate}]] · {s.position} · {s.stance} · {s.anchor}" for s in stances]
    return "\n".join(lines) + "\n"


# --- I/O -----------------------------------------------------------------------------------


def read_matrix(notes_root: Path) -> Matrix:
    matrix = Matrix()
    for path in sorted((notes_root / "10-debates").glob("*.md")):
        try:
            stances, problems = parse_stances(path.stem, read_note(path).body)
        except NoteFormatError as e:
            matrix.problems.append(f"{path.name}: {e}")
            continue
        matrix.stances += stances
        matrix.problems += [f"{path.name}: {p}" for p in problems]
    for source in {s.source for s in matrix.stances}:
        path = notes_root / "20-sources" / f"{source}.md"
        try:
            matrix.interests[source] = str(read_note(path).meta.get("interest") or "").strip()
        except (OSError, NoteFormatError):
            pass  # a missing source note shows as an unresolved link in Obsidian
    return matrix


def run(notes_root: Path) -> Matrix:
    matrix = read_matrix(notes_root)
    out = notes_root / "90-meta" / "matrix.md"
    out.write_text(render(matrix), encoding="utf-8")
    return matrix


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.parse_args(argv)

    matrix = run(NOTES_ROOT)
    for problem in matrix.problems:
        print(f"problem: {problem}")
    sources = {s.source for s in matrix.stances}
    debates = {s.debate for s in matrix.stances}
    print(f"{len(matrix.stances)} stances; {len(sources)} sources; {len(debates)} debates")
    return 1 if matrix.problems else 0


if __name__ == "__main__":
    sys.exit(main())
