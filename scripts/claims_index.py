"""Build the compact index that corpus-level work reads instead of the notes.

    uv run scripts/claims_index.py [--all]

Reads every `### Key claims` bullet in notes/20-sources/ and every debate in notes/10-debates/,
and writes three files to data/ (derived, gitignored):

- data/claims.md   all key claims, grouped by source, with source_type and interest
- data/pool.md     the claims of sources not yet in any debate (--all: every claim)
- data/debates.md  one line per debate: question and positions

A source is "in a debate" when any debate's `## Stances` links to it. Decided per source, not per
claim (docs/decisions.md, D25): intake comes in batches, and a batch's claims are what map-debates
places next.

A key claim must end in an anchor -- (p. N), (p. N, p. M), (pp. N-M), (¶ N) or (§ name). A claim
without one is reported and left out (CLAUDE.md §4.2). Exits 1 if any claim or note was malformed.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

from vault import NoteFormatError, read_note, sections, subsections

ROOT = Path(__file__).resolve().parent.parent
NOTES_ROOT = ROOT / "notes"
DATA_ROOT = ROOT / "data"

CLAIM = re.compile(r"^- (?P<text>.+?) (?P<anchor>\((?:pp?\.|¶|§) [^()]*\))\.?$")
WIKILINK = re.compile(r"\[\[([^\]|#]+)(?:[#|][^\]]*)?\]\]")
GENERATED = "Generated by scripts/claims_index.py; do not edit."


@dataclass(frozen=True)
class Source:
    name: str  # note filename without .md, as wikilinks name it
    source_type: str
    interest: str
    claims: list[str]  # each "text (anchor)"


@dataclass(frozen=True)
class Debate:
    name: str
    question: str
    positions: list[str]
    sources: set[str]  # source notes linked from ## Stances


@dataclass
class Index:
    sources: list[Source] = field(default_factory=list)
    debates: list[Debate] = field(default_factory=list)
    problems: list[str] = field(default_factory=list)


# --- pure transformation -------------------------------------------------------------------


def parse_claims(text: str) -> tuple[list[str], list[str]]:
    """Key-claim bullets as "text (anchor)", and the bullets that have no anchor."""
    claims, unanchored = [], []
    for line in text.splitlines():
        if not line.startswith("- "):
            continue
        m = CLAIM.match(line.rstrip())
        if m:
            claims.append(f"{m.group('text')} {m.group('anchor')}")
        else:
            unanchored.append(line.strip())
    return claims, unanchored


def link_target(target: str) -> str:
    """The note name a wikilink points to: no folders, no .md."""
    return Path(target.strip()).name.removesuffix(".md")


def parse_debate(name: str, meta: dict, body: str) -> Debate:
    parts = sections(body)
    positions = [p for p in subsections(parts.get("Positions", "")) if p]
    linked = {link_target(t) for t in WIKILINK.findall(parts.get("Stances", ""))}
    return Debate(name, str(meta.get("question") or "").strip(), positions, linked)


def _field(meta: dict, key: str) -> str:
    return str(meta.get(key) or "").strip()


def render_claims(title: str, sources: list[Source]) -> str:
    lines = [f"# {title}", "", GENERATED]
    for s in sources:
        header = " · ".join(filter(None, [f"[[{s.name}]]", s.source_type, s.interest]))
        lines += ["", f"## {header}", ""] + [f"- {c}" for c in s.claims]
    return "\n".join(lines) + "\n"


def render_debates(debates: list[Debate]) -> str:
    lines = ["# Debates", "", GENERATED, ""]
    if not debates:
        lines.append("No debates yet.")
    for d in debates:
        positions = " | ".join(d.positions) if d.positions else "none listed"
        lines.append(f"- [[{d.name}]] · {d.question or 'no question'} · positions: {positions}")
    return "\n".join(lines) + "\n"


def build(index: Index, all_claims: bool = False) -> dict[str, str]:
    """The three output files, by name."""
    with_claims = [s for s in index.sources if s.claims]
    in_debates = set().union(*(d.sources for d in index.debates))
    if all_claims:
        pool, pool_title = with_claims, "Pool: all claims (--all)"
    else:
        pool = [s for s in with_claims if s.name not in in_debates]
        pool_title = "Pool: claims of sources not yet in any debate"
    return {
        "claims.md": render_claims("Claims", with_claims),
        "pool.md": render_claims(pool_title, pool),
        "debates.md": render_debates(index.debates),
    }


# --- I/O -----------------------------------------------------------------------------------


def read_index(notes_root: Path) -> Index:
    index = Index()
    for path in sorted((notes_root / "20-sources").glob("*.md")):
        try:
            note = read_note(path)
            stated = sections(note.body).get("Stated by the source", "")
            claims, unanchored = parse_claims(subsections(stated).get("Key claims", ""))
        except NoteFormatError as e:
            index.problems.append(f"{path.name}: {e}")
            continue
        index.problems += [f"{path.name}: key claim without anchor: {c}" for c in unanchored]
        index.sources.append(
            Source(
                path.stem, _field(note.meta, "source_type"), _field(note.meta, "interest"), claims
            )
        )
    for path in sorted((notes_root / "10-debates").glob("*.md")):
        try:
            note = read_note(path)
            index.debates.append(parse_debate(path.stem, note.meta, note.body))
        except NoteFormatError as e:
            index.problems.append(f"{path.name}: {e}")
    return index


def run(notes_root: Path, data_root: Path, all_claims: bool = False) -> Index:
    index = read_index(notes_root)
    data_root.mkdir(parents=True, exist_ok=True)
    for name, text in build(index, all_claims).items():
        (data_root / name).write_text(text, encoding="utf-8")
    return index


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--all", action="store_true", help="put every claim in the pool")
    args = parser.parse_args(argv)

    index = run(NOTES_ROOT, DATA_ROOT, args.all)
    for problem in index.problems:
        print(f"problem: {problem}")

    with_claims = [s for s in index.sources if s.claims]
    in_debates = set().union(*(d.sources for d in index.debates))
    pooled = with_claims if args.all else [s for s in with_claims if s.name not in in_debates]
    without = [s.name for s in index.sources if not s.claims]
    print(
        f"{sum(len(s.claims) for s in with_claims)} claims from {len(with_claims)} sources; "
        f"{sum(len(s.claims) for s in pooled)} in the pool; {len(index.debates)} debates"
    )
    if without:
        print(f"sources without key claims (backfill with extract-claims): {', '.join(without)}")
    return 1 if index.problems else 0


if __name__ == "__main__":
    sys.exit(main())
